const featureToLabelMap = new Map<string, string>(
  ALL_SYMPTOMS.map((item) => [item.feature, item.label])
);

export function getSymptomLabel(feature: string): string {
  const match = featureToLabelMap.get(feature);
  if (match) return match;
  return feature.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

export function searchSymptoms(query: string, exclude: string[] = []): SymptomItem[] {
  const normalized = query.trim().toLowerCase();
  if (!normalized) return [];

  const excludeSet = new Set(exclude);

  return ALL_SYMPTOMS.filter((item) => {
    if (excludeSet.has(item.feature)) return false;
    if (item.label.toLowerCase().includes(normalized)) return true;
    if (item.feature.toLowerCase().includes(normalized)) return true;
    return item.keywords.some((kw) => kw.toLowerCase().includes(normalized));
  });
}
